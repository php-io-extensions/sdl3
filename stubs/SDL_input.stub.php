{
    public int $type = 0;

    public int $vendor_id = 0;

    public int $product_id = 0;

    public int $naxes = 0;

    public int $nbuttons = 0;

    public int $nhats = 0;

    public int $button_mask = 0;

    public int $axis_mask = 0;

    public string $name = '';
}

